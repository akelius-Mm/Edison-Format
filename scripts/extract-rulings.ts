// Builds src/cards/rulings.generated.ts, the judge's book (ui/duel/judge.ts): every 2010 ruling cited in the card
// scripts, by card. Per CLAUDE.md each card behaviour that depends on a ruling has a comment with its source URL next to
// it; this collects those comments.
//
// A ruling note is a block of consecutive `//` comment lines containing an https://edisonrul.ing/ or
// https://www.edisonformat.com/ link. It belongs to:
//   - the card the link's page is about (edisonrul.ing/cards/<letter>/<slug>.html), when that is a card in the pool, and
//   - the card whose definition the comment sits in (the nearest call above it naming a card: monster('…'), trap('…')…).
// The text is the comment without the link and the comment markers.
//
// Usage: npx tsx scripts/extract-rulings.ts          (writes the file)
//        npx tsx scripts/extract-rulings.ts --check  (fails if the file is out of date; part of npm test)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allCards } from '../src/cards';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/cards/rulings.generated.ts');
const DIRS = ['src/cards/sets', 'src/cards'];
const URL_RE = /https:\/\/(?:edisonrul\.ing|www\.edisonformat\.com)\/[^\s)"'`,;]*[^\s)"'`,;.]/;

const names = new Set(allCards().map((c) => c.name));
const slug = (n: string) =>
  n
    .toLowerCase()
    .replace(/['’"!?.,:]/g, '')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const bySlug = new Map<string, string>();
for (const n of names) bySlug.set(slug(n), n);

type Note = { text: string; url: string };
const book = new Map<string, Note[]>();
const add = (card: string, note: Note) => {
  const list = book.get(card) ?? [];
  if (!list.some((x) => x.text === note.text)) list.push(note);
  book.set(card, list);
};

/** Words that only make sense to someone reading the code. */
const CODE = /src\/|`|\b(ctx|dataMod|canActivate|eventFilter|condition|flags?|EffectDef|query|engine|APPROX|SOVR:|ABPF:|helper|script|uid|data\.\w+|true|false|null)\b/;

/** Keep the sentences a player can read; drop the ones about the code. */
function playerText(text: string) {
  return text
    .replace(/\([^()]*(?:src\/|`)[^()]*\)/g, '')
    .split(/(?<=[.!?])\s+(?=[A-Z"“(])/)
    .filter((sen) => !CODE.test(sen))
    .join(' ')
    .replace(/[;,]\s*see\s*$/i, '.')
    .replace(/\s+/g, ' ')
    .replace(/\s+([.,;])/g, '$1')
    .trim();
}

function clean(lines: string[], url: string) {
  return lines
    .join(' ')
    .replace(url, ' ')
    .replace(/https?:\/\/\S+/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/^[\s—:–-]+|[\s—:–(-]+$/g, '')
    .replace(/\(\s*\)/g, '')
    .replace(/\(\s*[,;]\s*/g, '(')
    .replace(/\s+([.,;])/g, '$1')
    .replace(/ — —/g, ' —')
    .trim();
}

const files = DIRS.flatMap((d) =>
  readdirSync(join(ROOT, d))
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.generated.ts'))
    .map((f) => join(d, f)),
);
for (const rel of files) {
  const lines = readFileSync(join(ROOT, rel), 'utf8').split('\n');
  let current: string | null = null;
  const defAt: (string | null)[] = [];
  for (const line of lines) {
    // a call that names a card starts (or continues) that card's definition
    for (const m of line.matchAll(/\b[A-Za-z]+\(\s*(['"])((?:(?!\1).)+)\1/g)) if (names.has(m[2])) current = m[2];
    defAt.push(current);
  }
  const isComment = (i: number) => /^\s*\/\//.test(lines[i] ?? '');
  for (let i = 0; i < lines.length; i++) {
    if (!isComment(i)) continue;
    const m = URL_RE.exec(lines[i]);
    if (!m) continue;
    let a = i;
    let b = i;
    while (a > 0 && isComment(a - 1) && !URL_RE.test(lines[a - 1])) a--;
    while (b + 1 < lines.length && isComment(b + 1) && !URL_RE.test(lines[b + 1])) b++;
    const block = lines.slice(a, b + 1).map((l) => l.replace(/^\s*\/\/\s?/, ''));
    const url = m[0];
    const text = playerText(clean(block, url));
    if (text.length < 20) continue;
    const page = /edisonrul\.ing\/cards\/[a-z0-9]\/([a-z0-9-]+)\.html/.exec(url)?.[1];
    const about = page ? bySlug.get(page) : undefined;
    const inside = defAt[i];
    if (about) add(about, { text, url });
    if (inside && inside !== about) add(inside, { text, url });
  }
}

const sorted = [...book.entries()].sort((x, y) => x[0].localeCompare(y[0]));
const body = `// Generated by scripts/extract-rulings.ts from the ruling comments in the card scripts. Do not edit by hand:
// change the comment next to the card's code and run \`npx tsx scripts/extract-rulings.ts\`.
export interface RulingNote {
  /** What the ruling says, in the words of the comment next to the card's code. */
  text: string;
  /** Its source: an edisonrul.ing page (2010 rulings) or edisonformat.com. */
  url: string;
}

/** 2010 rulings by card name. */
export const RULINGS: Record<string, RulingNote[]> = ${JSON.stringify(Object.fromEntries(sorted), null, 2)};
`;

if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== body) {
    console.log('rulings.generated.ts is out of date: run npx tsx scripts/extract-rulings.ts');
    process.exit(1);
  }
  console.log(`extract-rulings: up to date (${sorted.length} cards, ${sorted.reduce((a, [, l]) => a + l.length, 0)} notes)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}: ${sorted.length} cards, ${sorted.reduce((a, [, l]) => a + l.length, 0)} notes`);
}
