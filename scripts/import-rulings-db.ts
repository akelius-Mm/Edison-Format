// Indexes the rulings database (https://github.com/vivaria/edisonrul.ing, the source of https://edisonrul.ing) for the
// simulator: which database page is about each card of the pool, and the list of every page.
//   - src/cards/rulings-db.generated.ts: card name -> page (the judge links each card to its full 2010 rulings).
//   - scripts/data/edisonrul.ing-pages.json: every page and whether it has historical (2010) rulings
//     (scripts/rulings-db-test.ts checks every edisonrul.ing link cited in the code against it).
// Only the index is kept, not the rulings' text: the database publishes no license for it.
//
// Usage: git clone --depth 1 https://github.com/vivaria/edisonrul.ing <dir>
//        npx tsx scripts/import-rulings-db.ts <dir>
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allCards } from '../src/cards';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkout = process.argv[2];
if (!checkout) {
  console.error('Usage: npx tsx scripts/import-rulings-db.ts <edisonrul.ing checkout>');
  process.exit(2);
}
const CARDS = join(checkout, 'docs/source/cards');

/** Card names as the database titles them and as the pool names them, compared without punctuation or accents. */
const norm = (n: string) =>
  n
    .toLowerCase()
    .replace(/β/g, 'beta')
    .replace(/[ωΩ]/g, 'omega')
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '');

type Page = { path: string; title: string; historical: boolean };
const pages: Page[] = [];
for (const dir of readdirSync(CARDS, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  for (const f of readdirSync(join(CARDS, dir.name)).filter((x) => x.endsWith('.md')).sort()) {
    const md = readFileSync(join(CARDS, dir.name, f), 'utf8');
    const title = /^# (.+)$/m.exec(md)?.[1]?.trim() ?? '';
    const hist = md.split(/^## Edisonformat\.com \(Historical/m)[1] ?? '';
    pages.push({ path: `${dir.name}/${f.replace(/\.md$/, '')}`, title, historical: /^\*\s+\S/m.test(hist.split(/^## /m)[0]) });
  }
}
pages.sort((a, b) => a.path.localeCompare(b.path));

const byTitle = new Map<string, Page>();
for (const p of pages) if (p.title && !p.path.startsWith('misc/')) byTitle.set(norm(p.title), p);
const index: Record<string, string> = {};
const missing: string[] = [];
for (const name of [...new Set(allCards().map((c) => c.name))].sort()) {
  const p = byTitle.get(norm(name));
  if (p) index[name] = p.path;
  else missing.push(name);
}

const commit = execSync('git rev-parse HEAD', { cwd: checkout }).toString().trim();
const date = execSync('git log -1 --format=%cs', { cwd: checkout }).toString().trim();

writeFileSync(
  join(ROOT, 'src/cards/rulings-db.generated.ts'),
  `// Generated by scripts/import-rulings-db.ts from edisonrul.ing ${commit.slice(0, 7)} (${date}). Do not edit by hand.
/** The edisonrul.ing page about each card of the pool (cards/<path>.html), when the database has one. */
export const RULINGS_DB: Record<string, string> = ${JSON.stringify(index, null, 1)};

/** The page about \`name\` on edisonrul.ing: its historical (2010) and revised rulings. */
export function rulingsPage(name: string): string | undefined {
  const p = RULINGS_DB[name];
  return p ? \`https://edisonrul.ing/cards/\${p}.html\` : undefined;
}
`,
);
mkdirSync(join(ROOT, 'scripts/data'), { recursive: true });
// path -> 1 when the page has historical (2010) rulings, else 0; one page per line
const list = pages.map((p) => `  ${JSON.stringify(p.path)}: ${p.historical ? 1 : 0}`).join(',\n');
writeFileSync(join(ROOT, 'scripts/data/edisonrul.ing-pages.json'), `{\n "commit": "${commit}",\n "date": "${date}",\n "pages": {\n${list}\n }\n}\n`);
console.log(`import-rulings-db: ${pages.length} pages; ${Object.keys(index).length} pool cards have a page, ${missing.length} have none:`);
console.log('  ' + missing.join(' | '));
