// A third set of real tournament decklists for the Edison format (TCG card pool up to April 2010, March 2010 list).
//
// 1. Spring 2010 events:
//    - The last two published SJC Edison Top 16 lists (Ira D. Jones, Thai Bui), now complete thanks to Format
//      Library's copy of the Konami deck lists (tournament2.ts left them out because the YugiohTopDecks
//      transcriptions were short of 40).
//    - Lists from the Yu-Gi-Oh! Championship Series in Washington, DC (May 2010). It was played on the same March 2010
//      list as Edison but after The Shining Darkness came out; only lists that use no post-Edison cards are included
//      (no Infernities, no XX-Saber Darksoul / Boggart Knight). YugiohTopDecks gives only the month, so the date is
//      "2010-05". Placings are as published: 9th - 16th = Top 16, 17th - 32nd = Top 32.
// 2. Modern Edison Format events run by Format Library (formatlibrary.com) on the same card pool and list. Event,
//    date, player count and placing come from Format Library's own data (events.json / decks.json in
//    https://github.com/dwmcnelis/formatlibrary-backup). Pilots are the player handles Format Library records.
//
// Card counts are reproduced as published. The only changes are the ones noted above each deck: a card the simulator
// does not have yet (Dark End Dragon, Deck Devastation Virus, Vanity's Fiend, Soul Release, Twister, Mask of Restrict,
// Hero's Rule 2) is swapped for a close, era-typical stand-in, always in the Extra or Side Deck, never the Main Deck.

